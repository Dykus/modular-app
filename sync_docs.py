VERSION_060 = ("0.6.0", "Авторизация, роли, пользователи, руководство",
    "Вход и пароли (хеш), роли и права с человеческими описаниями, экраны «Роли» и «Пользователи», журнал входов и аудит, блокировка подбора пароля, safety-switch, модуль «Руководство» с печатью, регламент документации.")

def sync():
    from modules.help.models import HelpArticle, CATEGORIES
    from modules.changelog.models import ChangelogEntry
    from modules.versions.models import Release
    from modules.settings.models import Setting

    # 1) Spravki: obnovlyaem VSEGDA (upsert po nazvaniyu)
    for title, cat, order, body in HELP_ARTICLES:
        if cat not in CATEGORIES:
            cat = CATEGORIES[0]
        a = HelpArticle.query.filter_by(title=title).first()
        if not a:
            a = HelpArticle(title=title, category=cat, order=order, body=body,
                            edited_by="синхронизация документации")
            db.session.add(a)
        else:
            a.category = cat; a.order = order; a.body = body
            a.edited_by = "синхронизация документации"; a.updated_at = datetime.utcnow()
    db.session.commit()
    print("  help: statey sinhronizirovano = %d" % len(HELP_ARTICLES))

    # 2) Zhurnal izmeneniy: paket s markerom (ne dubliruem pri povtore)
    marker = Setting.query.get("docs_sync_v060")
    if marker is None or marker.value != "1":
        for typ, mod, desc in CHANGELOG_BATCH:
            db.session.add(ChangelogEntry(author="синхронизация документации",
                                          change_type=typ, module=mod, description=desc))
        db.session.add(Setting(key="docs_sync_v060", value="1"))
        db.session.commit()
        print("  changelog: zapisey dobavleno = %d" % len(CHANGELOG_BATCH))
    else:
        print("  changelog: partiya uzhe dobavlena ranee, propusk")

    # 3) Versii: releiz 0.6.0 odin raz, pomechaem tekushchim
    if not Release.query.filter_by(version="0.6.0").first():
        Release.query.update({"is_current": False})
        db.session.add(Release(version=VERSION_060[0], title=VERSION_060[1],
                               notes=VERSION_060[2], status="released", is_current=True))
        db.session.commit()
        print("  versions: releiz 0.6.0 sozdan i pomachen tekushchim")
    else:
        print("  versions: releiz 0.6.0 uzhe sushchestvuet, propusk")

if __name__ == "__main__":
    app = create_app()
    with app.app_context():
        sync()
    print("Sinhronizaciya dokumentacii zavershena.")
