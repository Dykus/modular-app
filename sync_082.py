CHANGELOG_BATCH = [
("added", "manual", "Новый раздел руководства «Совместимость: какие компьютеры и браузеры подходят» — простыми словами, с частыми вопросами."),
("added", "help", "Статья справки «Какие компьютеры и браузеры подходят» (выжимка раздела совместимости)."),
]

def sync():
    from modules.help.models import HelpArticle
    from modules.manual.models import ManualSection
    from modules.changelog.models import ChangelogEntry
    from modules.versions.models import Release
    from modules.settings.models import Setting

    s = ManualSection.query.filter_by(code=MANUAL_CODE).first()
    if not s:
        s = ManualSection(code=MANUAL_CODE, title=MANUAL_TITLE, order=115,
                          body=MANUAL_BODY, updated_by="синхронизация документации")
        db.session.add(s)
    else:
        s.title = MANUAL_TITLE; s.order = 115; s.body = MANUAL_BODY
        s.updated_by = "синхронизация документации"; s.updated_at = datetime.utcnow()

    a = HelpArticle.query.filter_by(title=HELP_TITLE).first()
    if not a:
        a = HelpArticle(title=HELP_TITLE, category="Техническое", order=2, body=HELP_BODY,
                        edited_by="синхронизация документации")
        db.session.add(a)
    else:
        a.body = HELP_BODY; a.edited_by = "синхронизация документации"; a.updated_at = datetime.utcnow()
    db.session.commit()
    print("  docs: razdel rukovodstva + statya spravki 'Sovmestimost' dobavleny")

    marker = db.session.get(Setting, "docs_sync_v082")
    if marker is None or marker.value != "1":
        for typ, mod, desc in CHANGELOG_BATCH:
            db.session.add(ChangelogEntry(author="синхронизация документации",
                                          change_type=typ, module=mod, description=desc))
        db.session.add(Setting(key="docs_sync_v082", value="1"))
        db.session.commit()
        print("  changelog: zapisey dobavleno = %d" % len(CHANGELOG_BATCH))
    else:
        print("  changelog: partiya 0.8.2 uzhe byla, propusk")

    if not Release.query.filter_by(version="0.8.2").first():
        Release.query.update({"is_current": False})
        db.session.add(Release(version="0.8.2",
            title="Справка о совместимости",
            notes="В руководстве и справке появился раздел о совместимости простыми словами: какие ОС подходят для сервера, почему XP и Server 2003 не подходят, какие браузеры работают, что делать со старыми компьютерами.",
            status="released", is_current=True))
        db.session.commit()
        print("  versions: releiz 0.8.2 sozdan i pomachen tekushchim")
    else:
        print("  versions: releiz 0.8.2 uzhe est")

if __name__ == "__main__":
    app = create_app()
    with app.app_context():
        sync()
    print("Sinhronizaciya 0.8.2 zavershena.")
